"""Different navigation tasks for initial discovery and bounded follow-up."""


def navigation(inputs, instructions, tools):
    if inputs.get("evidence_followup"):
        # The saved plan contains only unresolved obligations. Initial discovery
        # priorities must not displace them, but all proof contracts still apply.
        return (
            instructions
            + tools
            + (
                "\nЭто целевой дополнительный проход по evidence_followup.actions, а не новая первичная проверка. "
                "Выбери до четырёх чтений или поисковых запросов для этих открытых требований. "
                "Если открыта только применимость нормы, характеристика материала или функция машины, "
                "не начинай повторный поиск площадей и итогов таблиц. "
                "Ищи геометрию только для открытого числового требования или конкретного нового противоречия источников. "
                "Сохранённые числовые основания не доказывают свойства материала и применимость нормы. "
                "Ссылки из previous_review_items — навигация; используй первичные источники и проверку области применения. "
                "Если нужны новые чтения: summary до 200 символов, items=[], parameters=[], requests. "
                "Если сохранённых источников достаточно, выполни полноценную проверку по исходным правилам без новых чтений. "
                "Не подтверждай открытый аспект только потому, что его геометрия уже проверена. "
                "Повторный OCR запрещён."
            )
        )
    if inputs.get("shared_project_facts"):
        return (
            instructions
            + tools
            + (
                "\nЭто проверка с повторно проверенными буквальными проектными фактами прежнего прохода. "
                "Предыдущие статусы и нормативные выводы не перенесены; принадлежность текущему предмету "
                "и все действующие правила доказательств проверяй самостоятельно. "
                "Если переданных первичных источников достаточно, выполни полную проверку сейчас без новых чтений. "
                "Если не хватает конкретного основания, выбери до четырёх адресных requests; "
                "не начинай повторно искать уже переданные площадь, толщину или итог только ради нового запроса."
            )
        )
    return tools + (
        "\nСейчас ТОЛЬКО выбери до четырёх точных чтений. Приоритет: проектная конструкция, "
        "итоговые строки ведомости с подходящими заголовками columns, затем норматив. "
        "Используй row_ids из total_rows и column_ids подходящего материала/единицы. "
        "Начало таблицы без чисел не заменяет чтение итогов. Не проверяй всю позицию на этом шаге. "
        "summary до 200 символов, items=[], parameters=[], requests. "
        "На следующем шаге выполни проверку по полученным данным."
        "\nvor_layer_group.height — сумма технологических слоёв одной конструкции ВОР в см; "
        "выбирай проектный столбец полной толщины, а не требуй отдельный столбец каждой технологической операции."
        "\nprepared_schedule_candidates — только навигация, а не подтверждённое основание. "
        "Проверь предложенные read_requests и выбери нужные чтения; запроси норматив по смыслу работы и условиям. "
        "Наличие готовой суммы доказывает только арифметику, а принадлежность конструкции и применимость норм "
        "должен установить ты по прочитанным источникам."
    )
